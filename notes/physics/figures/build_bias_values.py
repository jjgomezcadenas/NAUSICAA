#!/usr/bin/env python3
"""Export manuscript bias settings and rounding checks from the saved study."""
from pathlib import Path
import hashlib
import json
import h5py

HERE = Path(__file__).resolve()
ROOT = HERE.parents[3]
OUT = HERE.parents[1] / "generated"


def main():
    source = ROOT / "results/ltspice/bias_sensitivity/analysis.h5"
    with h5py.File(source) as h:
        a = dict(h["paper_rounded_4"].attrs)
        assert a["signal_refinement_error"] < 1e-3
        assert a["noise_refinement_error"] < 1e-3
        values = {
            "SpiceMthreeGateV": f"{a['m3_gate_V']:.4f}",
            "SpiceMfourGateV": f"{a['m4_gate_V']:.4f}",
            "SpiceBiasRoundingEncPercent": f"{abs(a['ENC_relative_to_nominal']-1)*100:.2f}",
            "SpiceBiasRoundingGainPercent": f"{abs(a['gain_relative_to_nominal']-1)*100:.2f}",
        }
    (OUT / "spice_bias_values.tex").write_text(
        "% Generated by figures/build_bias_values.py from paper_rounded_4.\n"
        + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in values.items()))
    provenance = {
        "source": str(source.relative_to(ROOT)),
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "case": "paper_rounded_4",
        "generator": str(HERE.relative_to(ROOT)),
        "generator_sha256": hashlib.sha256(HERE.read_bytes()).hexdigest(),
        "values": values,
    }
    (OUT / "spice_bias_provenance.json").write_text(json.dumps(provenance, indent=2)+"\n")


if __name__ == "__main__":
    main()
