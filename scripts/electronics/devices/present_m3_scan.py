'''
        replacements={'TABLE':'\n'.join(table),'DETAIL':'\n'.join(detail),'NOISE':'\n'.join(noise),'CURRENT':f'{maxcurrent:.3g}','OUTPUT':f'{maxoutput*1e6:.3g}','THRESHOLDS':'\n\n'.join(thresholds)}
        for k,v in replacements.items():text=text.replace('@'+k+'@',v)
        (out/'report.tex').write_text(text)
        (result/'README.md').write_text('''# M3 optimization with provisional M4 x4

