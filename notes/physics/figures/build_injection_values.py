#!/usr/bin/env python3
"""Export the selected circuit's saved injection ENC for the comparison appendix."""
from pathlib import Path
import hashlib
import json
import h5py

HERE = Path(__file__).resolve()
ROOT = HERE.parents[3]
OUT = HERE.parents[1] / "generated"


def main():
    source = ROOT / "results/ltspice/m3_scan/analysis.h5"
    with h5py.File(source) as h:
        cases = [k for k in h if h[k].attrs["linear_scale"] == 4]
        assert len(cases) == 1
        case = cases[0]
        a = dict(h[case].attrs)
        for check in ("injection_transient_error", "injection_spectral_error",
                      "injection_quadrature_error", "injection_gain_10_vs_100_relative"):
            assert a[check] < 1e-3, check
        values = {"SpiceInjectionEnc": f"{a['injection_enc_e']:.1f}",
                  "SpiceInjectionCalibration": str(int(a['injection_calibration_electrons']))}
    (OUT / "spice_injection_values.tex").write_text(
        "% Generated by figures/build_injection_values.py from the M3 x4 study.\n"
        + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in values.items()))
    provenance = {"source": str(source.relative_to(ROOT)), "case": case,
                  "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                  "generator": str(HERE.relative_to(ROOT)),
                  "generator_sha256": hashlib.sha256(HERE.read_bytes()).hexdigest(),
                  "values": values}
    (OUT / "spice_injection_provenance.json").write_text(json.dumps(provenance, indent=2)+"\n")


if __name__ == "__main__":
    main()
