'''
        threshold=''
        if 'verified_N_snr5' in best:
            threshold=f"The selected adjusted variant (dimension multiplier {best['linear_scale']}) reaches $S/N>5$ at {best['verified_N_snr5']} ions; adjacent integer counts are verified at both timestep resolutions."
        text=text.replace('\\section*{Numerical checks and reproduction}',threshold+'\n\\section*{Numerical checks and reproduction}')
        text=text.replace('@TABLE@','\n'.join(table)).replace('@DETAILS@','\n'.join(details))
        (out/'report.tex').write_text(text)
        (result/'README.md').write_text('''# M4 geometry and bias scan

